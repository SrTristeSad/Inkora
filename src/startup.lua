    self.draft.width=tostring(p.w)
    self.draft.height=tostring(p.h)
    self.draft.preset=index
    self.draft.focus=nil
    self.error=nil
end
function Startup:validate()
    local d=self.draft
    local w,h=tonumber(d.width),tonumber(d.height)
    if not w or not h or w%1~=0 or h%1~=0 or w<64 or h<64 or w>4096 or h>4096 then
        self.error="Largura e altura devem estar entre 64 e 4096 pixels."
        return nil
    end
    self.error=nil
    return w,h
end
function Startup:submit(app)
    local w,h=self:validate()
    if not w then return false end
    return app:createArtwork(w,h,self.draft.name)
end
