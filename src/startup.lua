-- Inkora launcher: title -> local gallery -> new canvas -> native editor.
-- Functional reverse engineering of the observable ibisPaint entry workflow.
-- Original Inkora colors/marks; no third-party logos, assets, or art.
local Document=require("src.document")
local Startup={}
Startup.__index=Startup
local C={
    bg={0.070,0.103,0.176},deep={0.045,0.072,0.131},
    panel={0.112,0.155,0.235},raised={0.160,0.208,0.294},
    light={0.96,0.971,0.987},muted={0.64,0.74,0.84},
    accent={0.37,0.84,0.91},gold={1.0,0.76,0.48},
    stroke={0.24,0.32,0.42},white={1,1,1},
}
local PRESETS={
    {name="Quadrado HD",w=1280,h=1280,detail="1:1"},
    {name="Retrato",w=1080,h=1920,detail="9:16"},
    {name="Paisagem Full HD",w=1920,h=1080,detail="16:9"},
    {name="Ilustracao",w=1800,h=2400,detail="3:4"},
    {name="Quadrado leve",w=640,h=640,detail="1:1"},
    {name="Tela horizontal",w=2048,h=1536,detail="4:3"},
    {name="Pixel art",w=256,h=256,detail="1:1"},
}
local function clamp(x,a,b) return math.max(a,math.min(b,x)) end
local function inside(x,y,r) return x>=r.x and y>=r.y and x<r.x+r.w and y<r.y+r.h end
local function drawRect(x,y,w,h,c,r)
    love.graphics.setColor(c)
    love.graphics.rectangle("fill",x,y,w,h,r or 0,r or 0)
end
local function lineRect(x,y,w,h,c,r)
    love.graphics.setColor(c)
    love.graphics.setLineWidth(1.2)
    love.graphics.rectangle("line",x,y,w,h,r or 0,r or 0)
end
function Startup.new()
    return setmetatable({
        hits={},galleryScroll=0,thumbnailCache={},projects={},
        draft={name="Meu desenho",width="1280",height="1280",preset=1,focus=nil},
        fonts={
            logo=love.graphics.newFont(56),
            title=love.graphics.newFont(31),
            heading=love.graphics.newFont(21),
            body=love.graphics.newFont(16),
            small=love.graphics.newFont(13),
        },
        error=nil,
    },Startup)
end
function Startup:label(text,x,y,font,color,width,align)
    love.graphics.setColor(color or C.light)
    love.graphics.setFont(font or self.fonts.body)
    if width then love.graphics.printf(tostring(text),x,y,width,align or "left")
    else love.graphics.print(tostring(text),x,y) end
end
function Startup:hit(x,y,w,h,kind,action)
    self.hits[#self.hits+1]={x=x,y=y,w=w,h=h,kind=kind,action=action}
end
function Startup:button(text,x,y,w,h,kind,action,primary)
    local mx,my=love.mouse.getPosition()
    local hover=inside(mx,my,{x=x,y=y,w=w,h=h})
    drawRect(x,y,w,h,primary and C.accent or hover and C.raised or C.panel,12)
    if not primary then lineRect(x+0.5,y+0.5,w-1,h-1,C.stroke,12) end
    self:label(text,x+8,y+(h-self.fonts.body:getHeight())/2,
        self.fonts.body,primary and C.deep or C.light,w-16,"center")
    self:hit(x,y,w,h,kind,action)
end
function Startup:refreshGallery()
    self.projects=Document.listProjects()
    self.galleryScroll=0
    self.thumbnailCache={}
end
function Startup:openGallery(app)
    self:refreshGallery()
    app.screen="gallery"
    self.error=nil
end
function Startup:openCreate(app)
    self.draft={name="Meu desenho",width="1280",height="1280",preset=1,focus=nil}
    self.error=nil
    app.screen="create"
end
function Startup:drawBackground(w,h)
    love.graphics.clear(C.deep)
    drawRect(0,0,w,h,C.bg)
    -- Atmospheric concentric rings, generated by Inkora rather than art files.
    love.graphics.setColor(0.14,0.24,0.36,0.35)
    for radius=220,840,150 do
        love.graphics.setLineWidth(1)
        love.graphics.circle("line",w*0.83,h*0.43,radius)
    end
    drawRect(0,h-43,w,43,C.deep)
end
function Startup:mark(cx,cy,r)
    love.graphics.setColor(C.accent)
    love.graphics.circle("fill",cx,cy,r)
    love.graphics.setColor(C.bg)
    love.graphics.arc("fill",cx+r*0.25,cy-r*0.24,r*0.69,0.38,5.04)
    love.graphics.setColor(C.gold)
    love.graphics.circle("fill",cx-r*0.48,cy+r*0.40,r*0.16)
end
function Startup:openLatest(app)
    if #self.projects>0 then app:openArtwork(self.projects[1].key) end
end
function Startup:drawHome(app,w,h)
    local cx=w/2
    self:mark(cx,h*0.27,55)
    self:label("inkora",cx-240,h*0.37,self.fonts.logo,C.light,480,"center")
    self:label("Crie, organize e continue suas ilustracoes",
        cx-300,h*0.37+72,self.fonts.body,C.muted,600,"center")
    local cw,gap=250,24
    local left=cx-(cw*3+gap*2)/2
    local top=math.min(h*0.58,h-255)
    local cards={
        {title="Minha galeria",sub="Ver e continuar suas artes",kind="open-gallery",
            action=function()self:openGallery(app)end},
        {title="Novo desenho",sub="Criar uma tela em branco",kind="open-create",
            action=function()self:openCreate(app)end},
    }
    for i,item in ipairs(cards) do
        local x=left+(i-1)*(cw+gap)
        drawRect(x,top,cw,145,C.panel,18)
        lineRect(x,top,cw,145,C.stroke,18)
        if i==1 then
            for j=0,2 do
                drawRect(x+30+j*12,top+27+j*5,41,38,C.raised,5)
                lineRect(x+30+j*12,top+27+j*5,41,38,C.muted,5)
            end
        else
            love.graphics.setColor(C.accent)
            love.graphics.setLineWidth(4)
            love.graphics.line(x+51,top+30,x+51,top+70)
            love.graphics.line(x+31,top+50,x+71,top+50)
        end
        self:label(item.title,x+14,top+87,self.fonts.heading,C.light,cw-28,"center")
        self:label(item.sub,x+7,top+118,self.fonts.small,C.muted,cw-14,"center")
        self:hit(x,top,cw,145,item.kind,item.action)
    end
    local third=left+2*(cw+gap)
    drawRect(third,top,cw,145,C.panel,18)
    lineRect(third,top,cw,145,C.stroke,18)
    self:label("Ultima obra",third+20,top+27,self.fonts.heading,C.light,cw-40,"center")
    if #self.projects>0 then
        local latest=self.projects[1]
        self:label(latest.name,third+16,top+69,self.fonts.body,C.accent,cw-32,"center")
        self:label("Clique para continuar",third+16,top+111,self.fonts.small,C.muted,cw-32,"center")
        self:hit(third,top,cw,145,"open-latest",function()self:openLatest(app)end)
    else
        self:label("Sem trabalhos ainda",third+16,top+84,self.fonts.body,C.muted,cw-32,"center")
    end
    self:label(("%d %s salvos neste dispositivo"):format(#self.projects,
        #self.projects==1 and "trabalho" or "trabalhos"),
        cx-240,h-30,self.fonts.small,C.muted,480,"center")
end
function Startup:thumbnail(project)
    if not project.preview then return nil end
    local key=project.key
    if self.thumbnailCache[key]==false then return nil end
    if self.thumbnailCache[key] then return self.thumbnailCache[key] end
    local ok,img=pcall(love.graphics.newImage,project.preview)
    if ok then
        img:setFilter("linear","linear")
        self.thumbnailCache[key]=img
        return img
    end
    self.thumbnailCache[key]=false
    return nil
end
function Startup:drawGallery(app,w,h)
    self:button("<  Inicio",40,29,140,42,"back-home",function()app.screen="home"end)
    self:label("Minha galeria",54,103,self.fonts.title,C.light)
    self:label(("%d %s"):format(#self.projects,#self.projects==1 and "obra" or "obras"),
        57,141,self.fonts.small,C.muted)
    self:button("+  Novo desenho",w-272,33,226,44,"open-create",
        function()self:openCreate(app)end,true)
    if #self.projects==0 then
        local center=w/2
        drawRect(center-115,h*0.35,230,175,C.panel,17)
        self:mark(center,h*0.35+77,29)
        self:label("Sua galeria esta vazia",center-255,h*0.35+207,
            self.fonts.heading,C.light,510,"center")
        self:label("Crie o primeiro desenho para comecar sua colecao.",
            center-300,h*0.35+249,self.fonts.body,C.muted,600,"center")
        self:button("+ Criar meu primeiro desenho",center-172,
            math.min(h-116,h*0.35+299),344,50,"empty-create",
            function()self:openCreate(app)end,true)
        return
    end
    local gap,margin,available=19,52,w-104
    local columns=math.max(2,math.floor((available+gap)/257))
    local cw=(available-(columns-1)*gap)/columns
    local imageH=math.min(195,cw*0.70)
    local ch=imageH+89,top=191
    local rows=math.ceil(#self.projects/columns)
    local viewportHeight=h-top-30
    self.galleryMaxScroll=math.max(0,rows*(ch+gap)-gap-viewportHeight)
    self.galleryScroll=clamp(self.galleryScroll,0,self.galleryMaxScroll)
    love.graphics.setScissor(margin,top,available,viewportHeight)
    for index,project in ipairs(self.projects) do
        local col=(index-1)%columns
        local row=math.floor((index-1)/columns)
        local x=margin+col*(cw+gap)
        local y=top+row*(ch+gap)-self.galleryScroll
        if y+ch>top and y<top+viewportHeight then
            drawRect(x,y,cw,ch,C.panel,12)
            drawRect(x+8,y+8,cw-16,imageH,C.light,8)
            local img=self:thumbnail(project)
            if img then
                local iw,ih=img:getDimensions()
                local s=math.min((cw-16)/iw,imageH/ih)
                love.graphics.setColor(C.white)
                love.graphics.draw(img,x+(cw-iw*s)/2,y+8+(imageH-ih*s)/2,0,s,s)
            else
                self:label("INKORA",x+18,y+imageH/2,self.fonts.heading,
                    C.raised,cw-36,"center")
            end
            self:label(project.name,x+13,y+imageH+17,
                self.fonts.body,C.light,cw-26)
            self:label(project.width and
                    (project.width.." x "..project.height.." px") or "Projeto Inkora",
                x+13,y+imageH+48,self.fonts.small,C.muted,cw-26)
            self:hit(x,y,cw,ch,"open-artwork",
                function()app:openArtwork(project.key)end)
        end
    end
    love.graphics.setScissor()
    if self.galleryMaxScroll>0 then
        local track=viewportHeight
        local grip=math.max(30,track*viewportHeight/(viewportHeight+self.galleryMaxScroll))
        drawRect(w-18,top+track*(self.galleryScroll/(viewportHeight+self.galleryMaxScroll)),
            5,grip,C.accent,3)
    end
end
function Startup:choosePreset(index)
    local p=PRESETS[index]
    if not p then return end
    self.draft.width=tostring(p.w)
    self.draft.height=tostring(p.h)
    self.draft.preset=index
    self.draft.focus=nil
    self.error=nil
end
function Startup:validate()
    local d=self.draft
    local w,h=tonumber(d.width),tonumber(d.height)
    if not w or not h or w%1~=0 or h%1~=0 or w<64 or h<64 or w>4096 or h>4096 then
        self.error="Largura e altura devem estar entre 64 e 4096 pixels."
        return nil
    end
    self.error=nil
    return w,h
end
function Startup:submit(app)
    local w,h=self:validate()
    if not w then return false end
    return app:createArtwork(w,h,self.draft.name)
end
function Startup:drawCreate(app,w,h)
    self:button("<  Galeria",40,27,150,43,"back-gallery",
        function()self:openGallery(app)end)
    self:label("Novo desenho",57,111,self.fonts.title,C.light)
    self:label("Escolha as dimensoes e crie sua tela.",
        58,151,self.fonts.body,C.muted)
    local left,top=53,212
    local listWidth=math.min(560,w*0.47)
    self:label("TAMANHOS RAPIDOS",left,top-30,self.fonts.small,C.accent)
    local rowH=56
    for i,p in ipairs(PRESETS) do
        local y=top+(i-1)*(rowH+6)
        local active=self.draft.preset==i
        drawRect(left,y,listWidth,rowH,active and C.raised or C.panel,10)
        if active then lineRect(left+1,y+1,listWidth-2,rowH-2,C.accent,10) end
        self:label(p.name,left+16,y+8,self.fonts.body,C.light)
        self:label(p.w.." x "..p.h.." px",left+16,y+30,self.fonts.small,C.muted)
        self:label(p.detail,left+listWidth-95,y+19,self.fonts.small,C.accent,80,"right")
        self:hit(left,y,listWidth,rowH,"preset-"..i,function()self:choosePreset(i)end)
    end
    local right=left+listWidth+38
    local rw=w-right-54
    drawRect(right,top,rw,248,C.panel,15)
    self:label("PREVIA DA TELA",right+20,top+18,self.fonts.small,C.muted)
    local dw,dh=tonumber(self.draft.width),tonumber(self.draft.height)
    local frameX,frameY=right+36,top+54
    local fw,fh=rw-72,160
    drawRect(frameX,frameY,fw,fh,C.deep,11)
    if dw and dh and dw>0 and dh>0 then
        local scale=math.min((fw-42)/dw,(fh-34)/dh)
        local aw,ah=dw*scale,dh*scale
        drawRect(frameX+(fw-aw)/2,frameY+(fh-ah)/2,aw,ah,C.light,2)
        lineRect(frameX+(fw-aw)/2,frameY+(fh-ah)/2,aw,ah,C.stroke,2)
    end
    self:label((self.draft.width.." x "..self.draft.height.." px"),
        right+20,top+214,self.fonts.body,C.light,rw-40,"center")
    local controlsY=top+279
    self:label("Largura (px)",right,controlsY,self.fonts.small,C.muted)
    self:label("Altura (px)",right+rw/2+7,controlsY,self.fonts.small,C.muted)
    for _,spec in ipairs({{"width",right},{"height",right+rw/2+7}}) do
        local field,x=spec[1],spec[2]
        local boxW=rw/2-10
        local active=self.draft.focus==field
        drawRect(x,controlsY+23,boxW,43,active and C.raised or C.panel,8)
        lineRect(x,controlsY+23,boxW,43,active and C.accent or C.stroke,8)
        self:label(self.draft[field]..(active and "|" or ""),
            x+14,controlsY+34,self.fonts.body,C.light)
        self:hit(x,controlsY+23,boxW,43,"focus-"..field,function()
            self.draft.focus=field;self.draft.preset=nil
        end)
    end
    self:button("Inverter orientacao",right,controlsY+80,rw,37,"swap-orientation",function()
        self.draft.width,self.draft.height=self.draft.height,self.draft.width
        self.draft.preset=nil
    end)
    local nameY=controlsY+126
    self:label("Nome do trabalho",right,nameY,self.fonts.small,C.muted)
    drawRect(right,nameY+20,rw,42,self.draft.focus=="name" and C.raised or C.panel,8)
    lineRect(right,nameY+20,rw,42,self.draft.focus=="name" and C.accent or C.stroke,8)
    self:label(self.draft.name..(self.draft.focus=="name" and "|" or ""),
        right+12,nameY+31,self.fonts.body,C.light,rw-24)
    self:hit(right,nameY+20,rw,42,"focus-name",function()self.draft.focus="name"end)
    if self.error then self:label(self.error,right,nameY+69,self.fonts.small,C.gold,rw) end
    self:button("Criar tela e desenhar",right,math.min(h-75,nameY+87),
        rw,48,"create-artwork",function()self:submit(app)end,true)
    self:label("Tamanhos ate 4096 x 4096 pixels",
        54,h-30,self.fonts.small,C.muted)
end
function Startup:draw(app)
    self.hits={}
    local w,h=love.graphics.getDimensions()
    self:drawBackground(w,h)
    if app.screen=="home" then self:drawHome(app,w,h)
    elseif app.screen=="gallery" then self:drawGallery(app,w,h)
    elseif app.screen=="create" then self:drawCreate(app,w,h)
    end
    if self.error and app.screen~="create" then
        self:label(self.error,32,h-29,self.fonts.small,C.gold,w-64)
    end
end
function Startup:click(x,y)
    for i=#self.hits,1,-1 do
        local hit=self.hits[i]
        if inside(x,y,hit) then
            hit.action()
            return true
        end
    end
    return false
end
function Startup:wheel(delta)
    if self.galleryMaxScroll and self.galleryMaxScroll>0 then
        self.galleryScroll=clamp(self.galleryScroll-delta*75,0,self.galleryMaxScroll)
    end
end
function Startup:keypressed(app,key)
    if app.screen=="gallery" and key=="escape" then app.screen="home";return true end
    if app.screen=="create" then
        if key=="escape" then self:openGallery(app);return true end
        local d=self.draft
        if key=="tab" then
            d.focus=d.focus=="width" and "height" or
                d.focus=="height" and "name" or "width"
            return true
        elseif key=="backspace" and d.focus then
            if d.focus=="name" then
                local utf8=require("utf8")
                local n=utf8.offset(d.name,-1)
                if n then d.name=d.name:sub(1,n-1) end
            else d[d.focus]=d[d.focus]:sub(1,-2);d.preset=nil end
            return true
        elseif key=="return" or key=="kpenter" then
            return self:submit(app)
        end
    end
    return false
end
function Startup:textinput(text)
    local d=self.draft
    if d.focus=="name" then
        d.name=(d.name..text:gsub("[\r\n\t]","")):sub(1,64)
    elseif d.focus=="width" or d.focus=="height" then
        d[d.focus]=(d[d.focus]..text:gsub("%D","")):sub(1,4)
        d.preset=nil
    end
end
return Startup
