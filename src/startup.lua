local function clamp(x,a,b) return math.max(a,math.min(b,x)) end
local function inside(x,y,r) return x>=r.x and y>=r.y and x<r.x+r.w and y<r.y+r.h end
local function drawRect(x,y,w,h,c,r)
    love.graphics.setColor(c)
    love.graphics.rectangle("fill",x,y,w,h,r or 0,r or 0)
end
local function lineRect(x,y,w,h,c,r)
    love.graphics.setColor(c)
    love.graphics.setLineWidth(1.2)
    love.graphics.rectangle("line",x,y,w,h,r or 0,r or 0)
end
function Startup.new()
    return setmetatable({
        hits={},galleryScroll=0,thumbnailCache={},projects={},
        galleryDetailKey=nil,gallerySelecting=false,gallerySelected={},
        galleryModal=nil,galleryMenu=false,notice=nil,
        galleryFolder="",folders=Folders.new(),newMenu=false,
        galleryDrag=nil,canvasScroll=0,folderTitlePress=nil,
        draft={name="Meu desenho",width="1280",height="1280",preset=1,focus=nil},
        fonts={
            logo=love.graphics.newFont(56),
            title=love.graphics.newFont(31),
            heading=love.graphics.newFont(21),
            body=love.graphics.newFont(16),
            small=love.graphics.newFont(13),
        },
        error=nil,
    },Startup)
end
function Startup:label(text,x,y,font,color,width,align)
    love.graphics.setColor(color or C.light)
    love.graphics.setFont(font or self.fonts.body)
    if width then love.graphics.printf(tostring(text),x,y,width,align or "left")
    else love.graphics.print(tostring(text),x,y) end
end
function Startup:hit(x,y,w,h,kind,action)
    self.hits[#self.hits+1]={x=x,y=y,w=w,h=h,kind=kind,action=action}
end
function Startup:button(text,x,y,w,h,kind,action,primary)
    local mx,my=love.mouse.getPosition()
    local hover=inside(mx,my,{x=x,y=y,w=w,h=h})
    drawRect(x,y,w,h,primary and C.accent or hover and C.raised or C.panel,12)
    if not primary then lineRect(x+0.5,y+0.5,w-1,h-1,C.stroke,12) end
    self:label(text,x+8,y+(h-self.fonts.body:getHeight())/2,
        self.fonts.body,primary and C.deep or C.light,w-16,"center")
    self:hit(x,y,w,h,kind,action)
end
function Startup:refreshGallery()
    self.projects=Document.listProjects()
    self.galleryScroll=0
    self.thumbnailCache={}
end
function Startup:openGallery(app,retainFolder)
    self:refreshGallery()
    if not retainFolder then self.galleryFolder="" end
    self.newMenu=false
    self.galleryDetailKey=nil
    self.gallerySelecting=false
    self.gallerySelected={}
    self.galleryModal=nil
    self.galleryMenu=false
    self.notice=nil
    app.screen="gallery"
    self.error=nil
end
function Startup:openCreate(app)
    self.draft={name="Meu desenho",width="1000",height="1000",preset=nil,focus=nil}
    self.canvasScroll=0
    self.error=nil
    self.newMenu=false
    self.galleryModal={kind="new",focus=nil,quality=0.5}
    if app then app.screen="gallery" end
end
function Startup:drawBackground(w,h)
    love.graphics.clear(C.deep)
    drawRect(0,0,w,h,C.bg)
    -- Atmospheric concentric rings, generated by Inkora rather than art files.
    love.graphics.setColor(0.14,0.24,0.36,0.35)
    for radius=220,840,150 do
        love.graphics.setLineWidth(1)
        love.graphics.circle("line",w*0.83,h*0.43,radius)
    end
    drawRect(0,h-43,w,43,C.deep)
end
function Startup:mark(cx,cy,r)
    love.graphics.setColor(C.accent)
    love.graphics.circle("fill",cx,cy,r)
    love.graphics.setColor(C.bg)
    love.graphics.arc("fill",cx+r*0.25,cy-r*0.24,r*0.69,0.38,5.04)
    love.graphics.setColor(C.gold)
    love.graphics.circle("fill",cx-r*0.48,cy+r*0.40,r*0.16)
end
function Startup:openLatest(app)
    if #self.projects>0 then app:openArtwork(self.projects[1].key) end
end
-- Home layout was measured against the observable ibisPaint title-screen
-- structure: cool blue title field, centered brand, two circular navigation
-- buttons, and a distinct darker lower content band. All Inkora branding is
-- original. No copied logos or promotional artwork.
local HOME_BLUE={0.146,0.278,0.435}
local HOME_DARK={0.085,0.174,0.281}
local HOME_OUTLINE={0.83,0.89,0.96}

-- The My Gallery icon is a drawing brush rather than a pencil:
-- its rounded handle points toward the TOP RIGHT, while the bristles point
-- toward the BOTTOM LEFT (the reverse of the incorrect earlier icon).
-- Drawn as original Inkora Lua vector shapes; no copied ibisPaint artwork.
local function drawGalleryBrush(cx,cy,radius)
    local u=radius*0.64
    love.graphics.push("all")
    love.graphics.translate(cx,cy)
    -- In screen coordinates, negative X with -45 deg rotation is down-left.
    -- The tip is on the negative-X end; the handle is on positive X.
    love.graphics.rotate(-math.pi/4)
    love.graphics.setColor(HOME_OUTLINE)
    love.graphics.setLineStyle("smooth")
    love.graphics.setLineJoin("bevel")
    love.graphics.setLineWidth(math.max(2,radius*0.028))

    -- Long, narrow body and rounded butt of the drawing brush.
    love.graphics.line(
        -u*0.30,-u*0.17,
         u*0.65,-u*0.17,
         u*0.78,-u*0.10,
         u*0.78, u*0.10,
         u*0.65, u*0.17,
        -u*0.30, u*0.17
    )
    love.graphics.line(-u*0.04,-u*0.075,u*0.52,-u*0.075)

    -- Ferrule connecting bristles to handle.
    love.graphics.rectangle("line",
        -u*0.49,-u*0.18,u*0.19,u*0.36,u*0.025,u*0.025)
    love.graphics.line(-u*0.42,-u*0.18,-u*0.42,u*0.18)

    -- Slim, tapered bristle tip, unmistakably at the LOWER-LEFT.
    love.graphics.line(
        -u*0.49,-u*0.17,
        -u*0.67,-u*0.14,
        -u*0.94,-u*0.015,
        -u*0.98,0,
        -u*0.94,u*0.015,
        -u*0.67,u*0.14,
        -u*0.49,u*0.17
    )
    love.graphics.pop()
end
function Startup:drawHome(app,w,h)
    -- The previous three large cards were not the reference's title layout.
    -- Scale the two navigation targets while preserving a predictable ratio.
    love.graphics.clear(HOME_BLUE)
    drawRect(0,0,w,h,HOME_BLUE)
    local separator=math.floor(h*0.595)
    drawRect(0,separator,w,h-separator,HOME_DARK)

    local titleY=math.max(28,math.floor(separator*0.13))
    self:label("inkora",w*0.15,titleY,self.fonts.logo,C.light,w*0.70,"center")
    self:label("PINTURA DIGITAL",w*0.20,titleY+72,
        self.fonts.small,HOME_OUTLINE,w*0.60,"center")
    self:label("DESKTOP",w-116,17,self.fonts.small,HOME_OUTLINE,99,"right")

    local radius=clamp(math.floor(math.min(w*0.073,h*0.086)),45,72)
    local offset=math.max(radius+48,math.min(205,w*0.16))
    local centerY=math.min(separator-109,math.max(titleY+163,separator*0.64))
    local buttons={
        {cx=w/2-offset,label="Minha Galeria",kind="open-gallery",
            action=function()self:openGallery(app)end,icon="brush"},
        {cx=w/2+offset,label="Galeria Online",kind="online-gallery",
            action=function()
                self.error="Galeria online: recurso ainda nao implementado no Inkora."
            end,icon="globe"},
    }
    for _,item in ipairs(buttons) do
        local x,y=item.cx,centerY
        local mx,my=love.mouse.getPosition()
        local hover=(mx-x)^2+(my-y)^2<radius*radius
        love.graphics.setLineWidth(hover and 2.4 or 1.4)
        love.graphics.setColor(HOME_OUTLINE)
        love.graphics.circle("line",x,y,radius)
        if hover then
            love.graphics.setColor(1,1,1,0.09)
            love.graphics.circle("fill",x,y,radius-1)
        end
        local g=radius*0.43
        if item.icon=="globe" then
            love.graphics.setColor(HOME_OUTLINE)
            love.graphics.setLineWidth(2)
            love.graphics.circle("line",x,y,g)
            love.graphics.ellipse("line",x,y,g*0.48,g)
            love.graphics.line(x-g,y,x+g,y)
            love.graphics.line(x-g*0.87,y-g*0.44,x+g*0.87,y-g*0.44)
            love.graphics.line(x-g*0.87,y+g*0.44,x+g*0.87,y+g*0.44)
        else
            drawGalleryBrush(x,y,radius)
        end
        self:label(item.label,x-radius-65,y+radius+14,
            self.fonts.body,C.light,(radius+65)*2,"center")
        self:hit(x-radius-14,y-radius-10,2*(radius+14),
            2*(radius+19),item.kind,item.action)
    end
    love.graphics.setLineWidth(1)

    -- ibisPaint's lower area is the daily public ranking. Inkora has no
    -- public ranking backend, so occupy the same visual region with REAL
    -- recent local artwork only, never fictitious rankings or fake uploads.
    self:label("Trabalhos recentes",w*0.15,separator+18,
        self.fonts.heading,C.light,w*0.70,"center")
    if #self.projects==0 then
        self:label("Seus desenhos aparecerao aqui apos serem criados.",
            w*0.2,separator+87,self.fonts.body,HOME_OUTLINE,w*0.6,"center")
        self:button("Abrir Minha Galeria",w/2-127,separator+143,
            254,46,"open-gallery-bottom",function()self:openGallery(app)end,false)
    else
        local columns=math.min(4,#self.projects)
        local gap=18
        local cardWidth=math.min(210,math.floor((w-112-(columns-1)*gap)/columns))
        local fullWidth=cardWidth*columns+(columns-1)*gap
        local left=(w-fullWidth)/2
        local cardY=separator+64
        local cardH=math.max(70,math.min(h-separator-106,175))
        for i=1,columns do
            local project=self.projects[i]
            local x=left+(i-1)*(cardWidth+gap)
            drawRect(x,cardY,cardWidth,cardH,C.light,3)
            local thumbnail=self:thumbnail(project)
            if thumbnail then
                local iw,ih=thumbnail:getDimensions()
                local scale=math.min((cardWidth-10)/iw,(cardH-10)/ih)
                love.graphics.setColor(1,1,1,1)
                love.graphics.draw(thumbnail,
                    x+(cardWidth-iw*scale)/2,
                    cardY+(cardH-ih*scale)/2,0,scale,scale)
            end
            self:label(project.name,x,cardY+cardH+10,
                self.fonts.small,C.light,cardWidth,"center")
            self:hit(x,cardY,cardWidth,cardH+36,"open-recent-"..i,
                function()app:openArtwork(project.key)end)
        end
    end
    if self.error then
        self:label(self.error,w*0.12,h-28,self.fonts.small,
            C.gold,w*0.76,"center")
    end
end
function Startup:thumbnail(project)
    if not project.preview then return nil end
    local key=project.key
    if self.thumbnailCache[key]==false then return nil end
    if self.thumbnailCache[key] then return self.thumbnailCache[key] end
    local ok,img=pcall(love.graphics.newImage,project.preview)
    if ok then
        img:setFilter("linear","linear")
        self.thumbnailCache[key]=img
        return img
    end
    self.thumbnailCache[key]=false
    return nil
end
