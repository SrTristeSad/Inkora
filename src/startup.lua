function Startup:draw(app)
    self.hits={}
    local w,h=love.graphics.getDimensions()
    self:drawBackground(w,h)
    if app.screen=="home" then self:drawHome(app,w,h)
    elseif app.screen=="gallery" then self:drawGallery(app,w,h)
    elseif app.screen=="create" then self:drawCreate(app,w,h)
    end
    if self.error and app.screen~="create" then
        self:label(self.error,32,h-29,self.fonts.small,C.gold,w-64)
    end
end
function Startup:click(x,y)
    for i=#self.hits,1,-1 do
        local hit=self.hits[i]
        if inside(x,y,hit) then
            hit.action()
            return true
        end
    end
    return false
end
function Startup:wheel(delta)
    if self.galleryMaxScroll and self.galleryMaxScroll>0 then
        self.galleryScroll=clamp(self.galleryScroll-delta*75,0,self.galleryMaxScroll)
    end
end
function Startup:keypressed(app,key)
    if app.screen=="gallery" and key=="escape" then app.screen="home";return true end
    if app.screen=="create" then
        if key=="escape" then self:openGallery(app);return true end
        local d=self.draft
        if key=="tab" then
            d.focus=d.focus=="width" and "height" or
                d.focus=="height" and "name" or "width"
            return true
        elseif key=="backspace" and d.focus then
            if d.focus=="name" then
                local utf8=require("utf8")
                local n=utf8.offset(d.name,-1)
                if n then d.name=d.name:sub(1,n-1) end
            else d[d.focus]=d[d.focus]:sub(1,-2);d.preset=nil end
            return true
        elseif key=="return" or key=="kpenter" then
            return self:submit(app)
        end
    end
    return false
end
function Startup:textinput(text)
    local d=self.draft
    if d.focus=="name" then
        d.name=(d.name..text:gsub("[\r\n\t]","")):sub(1,64)
    elseif d.focus=="width" or d.focus=="height" then
        d[d.focus]=(d[d.focus]..text:gsub("%D","")):sub(1,4)
        d.preset=nil
    end
end
return Startup
