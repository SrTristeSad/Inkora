local function clamp(x,a,b) return math.max(a,math.min(b,x)) end
local function inside(x,y,r) return x>=r.x and y>=r.y and x<r.x+r.w and y<r.y+r.h end
local function drawRect(x,y,w,h,c,r)
    love.graphics.setColor(c)
    love.graphics.rectangle("fill",x,y,w,h,r or 0,r or 0)
end
local function lineRect(x,y,w,h,c,r)
    love.graphics.setColor(c)
    love.graphics.setLineWidth(1.2)
    love.graphics.rectangle("line",x,y,w,h,r or 0,r or 0)
end
function Startup.new()
    return setmetatable({
        hits={},galleryScroll=0,thumbnailCache={},projects={},
        galleryDetailKey=nil,gallerySelecting=false,gallerySelected={},
        galleryModal=nil,galleryMenu=false,notice=nil,
        galleryFolder="",folders=Folders.new(),newMenu=false,
        galleryDrag=nil,
        draft={name="Meu desenho",width="1280",height="1280",preset=1,focus=nil},
        fonts={
            logo=love.graphics.newFont(56),
            title=love.graphics.newFont(31),
            heading=love.graphics.newFont(21),
            body=love.graphics.newFont(16),
            small=love.graphics.newFont(13),
        },
        error=nil,
    },Startup)
end
function Startup:label(text,x,y,font,color,width,align)
    love.graphics.setColor(color or C.light)
    love.graphics.setFont(font or self.fonts.body)
    if width then love.graphics.printf(tostring(text),x,y,width,align or "left")
    else love.graphics.print(tostring(text),x,y) end
end
function Startup:hit(x,y,w,h,kind,action)
    self.hits[#self.hits+1]={x=x,y=y,w=w,h=h,kind=kind,action=action}
end
function Startup:button(text,x,y,w,h,kind,action,primary)
    local mx,my=love.mouse.getPosition()
    local hover=inside(mx,my,{x=x,y=y,w=w,h=h})
    drawRect(x,y,w,h,primary and C.accent or hover and C.raised or C.panel,12)
    if not primary then lineRect(x+0.5,y+0.5,w-1,h-1,C.stroke,12) end
    self:label(text,x+8,y+(h-self.fonts.body:getHeight())/2,
        self.fonts.body,primary and C.deep or C.light,w-16,"center")
    self:hit(x,y,w,h,kind,action)
end
function Startup:refreshGallery()
    self.projects=Document.listProjects()
    self.galleryScroll=0
    self.thumbnailCache={}
end
function Startup:openGallery(app,retainFolder)
    self:refreshGallery()
    if not retainFolder then self.galleryFolder="" end
    self.newMenu=false
    self.galleryDetailKey=nil
    self.gallerySelecting=false
    self.gallerySelected={}
    self.galleryModal=nil
    self.galleryMenu=false
    self.notice=nil
    app.screen="gallery"
    self.error=nil
end
function Startup:openCreate(app)
    self.draft={name="Meu desenho",width="1280",height="1280",preset=1,focus=nil}
    self.error=nil
    app.screen="create"
end
function Startup:drawBackground(w,h)
    love.graphics.clear(C.deep)
    drawRect(0,0,w,h,C.bg)
    -- Atmospheric concentric rings, generated by Inkora rather than art files.
    love.graphics.setColor(0.14,0.24,0.36,0.35)
    for radius=220,840,150 do
        love.graphics.setLineWidth(1)
        love.graphics.circle("line",w*0.83,h*0.43,radius)
    end
    drawRect(0,h-43,w,43,C.deep)
end
function Startup:mark(cx,cy,r)
    love.graphics.setColor(C.accent)
    love.graphics.circle("fill",cx,cy,r)
    love.graphics.setColor(C.bg)
    love.graphics.arc("fill",cx+r*0.25,cy-r*0.24,r*0.69,0.38,5.04)
    love.graphics.setColor(C.gold)
    love.graphics.circle("fill",cx-r*0.48,cy+r*0.40,r*0.16)
end
function Startup:openLatest(app)
    if #self.projects>0 then app:openArtwork(self.projects[1].key) end
end
-- Home layout was measured against the observable ibisPaint title-screen
-- structure: cool blue title field, centered brand, two circular navigation
-- buttons, and a distinct darker lower content band. All Inkora branding is
-- original. No copied logos or promotional artwork.
local HOME_BLUE={0.146,0.278,0.435}
local HOME_DARK={0.085,0.174,0.281}
local HOME_OUTLINE={0.83,0.89,0.96}

-- The My Gallery icon is a drawing brush rather than a pencil:
-- its rounded handle points toward the TOP RIGHT, while the bristles point
-- toward the BOTTOM LEFT (the reverse of the incorrect earlier icon).
-- Drawn as original Inkora Lua vector shapes; no copied ibisPaint artwork.
local function drawGalleryBrush(cx,cy,radius)
    local u=radius*0.64
    love.graphics.push("all")
    love.graphics.translate(cx,cy)
    -- In screen coordinates, negative X with -45 deg rotation is down-left.
    -- The tip is on the negative-X end; the handle is on positive X.
    love.graphics.rotate(-math.pi/4)
    love.graphics.setColor(HOME_OUTLINE)
    love.graphics.setLineStyle("smooth")
    love.graphics.setLineJoin("bevel")
    love.graphics.setLineWidth(math.max(2,radius*0.028))

    -- Long, narrow body and rounded butt of the drawing brush.
    love.graphics.line(
        -u*0.30,-u*0.17,
         u*0.65,-u*0.17,
         u*0.78,-u*0.10,
         u*0.78, u*0.10,
         u*0.65, u*0.17,
        -u*0.30, u*0.17
    )
    love.graphics.line(-u*0.04,-u*0.075,u*0.52,-u*0.075)

    -- Ferrule connecting bristles to handle.
    love.graphics.rectangle("line",
        -u*0.49,-u*0.18,u*0.19,u*0.36,u*0.025,u*0.025)
    love.graphics.line(-u*0.42,-u*0.18,-u*0.42,u*0.18)

    -- Slim, tapered bristle tip, unmistakably at the LOWER-LEFT.
    love.graphics.line(
        -u*0.49,-u*0.17,
        -u*0.67,-u*0.14,
        -u*0.94,-u*0.015,
        -u*0.98,0,
        -u*0.94,u*0.015,
        -u*0.67,u*0.14,
        -u*0.49,u*0.17
    )
    love.graphics.pop()
end
function Startup:drawHome(app,w,h)
    -- The previous three large cards were not the reference's title layout.
    -- Scale the two navigation targets while preserving a predictable ratio.
    love.graphics.clear(HOME_BLUE)
    drawRect(0,0,w,h,HOME_BLUE)
    local separator=math.floor(h*0.595)
    drawRect(0,separator,w,h-separator,HOME_DARK)

    local titleY=math.max(28,math.floor(separator*0.13))
    self:label("inkora",w*0.15,titleY,self.fonts.logo,C.light,w*0.70,"center")
    self:label("PINTURA DIGITAL",w*0.20,titleY+72,
        self.fonts.small,HOME_OUTLINE,w*0.60,"center")
    self:label("DESKTOP",w-116,17,self.fonts.small,HOME_OUTLINE,99,"right")

    local radius=clamp(math.floor(math.min(w*0.073,h*0.086)),45,72)
    local offset=math.max(radius+48,math.min(205,w*0.16))
    local centerY=math.min(separator-109,math.max(titleY+163,separator*0.64))
    local buttons={
        {cx=w/2-offset,label="Minha Galeria",kind="open-gallery",
            action=function()self:openGallery(app)end,icon="brush"},
        {cx=w/2+offset,label="Galeria Online",kind="online-gallery",
            action=function()
                self.error="Galeria online: recurso ainda nao implementado no Inkora."
            end,icon="globe"},
    }
    for _,item in ipairs(buttons) do
        local x,y=item.cx,centerY
        local mx,my=love.mouse.getPosition()
        local hover=(mx-x)^2+(my-y)^2<radius*radius
        love.graphics.setLineWidth(hover and 2.4 or 1.4)
        love.graphics.setColor(HOME_OUTLINE)
        love.graphics.circle("line",x,y,radius)
        if hover then
            love.graphics.setColor(1,1,1,0.09)
            love.graphics.circle("fill",x,y,radius-1)
        end
        local g=radius*0.43
        if item.icon=="globe" then
            love.graphics.setColor(HOME_OUTLINE)
            love.graphics.setLineWidth(2)
            love.graphics.circle("line",x,y,g)
            love.graphics.ellipse("line",x,y,g*0.48,g)
            love.graphics.line(x-g,y,x+g,y)
            love.graphics.line(x-g*0.87,y-g*0.44,x+g*0.87,y-g*0.44)
            love.graphics.line(x-g*0.87,y+g*0.44,x+g*0.87,y+g*0.44)
        else
            drawGalleryBrush(x,y,radius)
        end
        self:label(item.label,x-radius-65,y+radius+14,
            self.fonts.body,C.light,(radius+65)*2,"center")
        self:hit(x-radius-14,y-radius-10,2*(radius+14),
            2*(radius+19),item.kind,item.action)
    end
    love.graphics.setLineWidth(1)

    -- ibisPaint's lower area is the daily public ranking. Inkora has no
    -- public ranking backend, so occupy the same visual region with REAL
    -- recent local artwork only, never fictitious rankings or fake uploads.
    self:label("Trabalhos recentes",w*0.15,separator+18,
        self.fonts.heading,C.light,w*0.70,"center")
    if #self.projects==0 then
        self:label("Seus desenhos aparecerao aqui apos serem criados.",
            w*0.2,separator+87,self.fonts.body,HOME_OUTLINE,w*0.6,"center")
        self:button("Abrir Minha Galeria",w/2-127,separator+143,
            254,46,"open-gallery-bottom",function()self:openGallery(app)end,false)
    else
        local columns=math.min(4,#self.projects)
        local gap=18
        local cardWidth=math.min(210,math.floor((w-112-(columns-1)*gap)/columns))
        local fullWidth=cardWidth*columns+(columns-1)*gap
        local left=(w-fullWidth)/2
        local cardY=separator+64
        local cardH=math.max(70,math.min(h-separator-106,175))
        for i=1,columns do
            local project=self.projects[i]
            local x=left+(i-1)*(cardWidth+gap)
            drawRect(x,cardY,cardWidth,cardH,C.light,3)
            local thumbnail=self:thumbnail(project)
            if thumbnail then
                local iw,ih=thumbnail:getDimensions()
                local scale=math.min((cardWidth-10)/iw,(cardH-10)/ih)
                love.graphics.setColor(1,1,1,1)
                love.graphics.draw(thumbnail,
                    x+(cardWidth-iw*scale)/2,
                    cardY+(cardH-ih*scale)/2,0,scale,scale)
            end
            self:label(project.name,x,cardY+cardH+10,
                self.fonts.small,C.light,cardWidth,"center")
            self:hit(x,cardY,cardWidth,cardH+36,"open-recent-"..i,
                function()app:openArtwork(project.key)end)
        end
    end
    if self.error then
        self:label(self.error,w*0.12,h-28,self.fonts.small,
            C.gold,w*0.76,"center")
    end
end
function Startup:thumbnail(project)
    if not project.preview then return nil end
    local key=project.key
    if self.thumbnailCache[key]==false then return nil end
    if self.thumbnailCache[key] then return self.thumbnailCache[key] end
    local ok,img=pcall(love.graphics.newImage,project.preview)
    if ok then
        img:setFilter("linear","linear")
        self.thumbnailCache[key]=img
        return img
    end
    self.thumbnailCache[key]=false
    return nil
end
-- The My Gallery screen follows the app's observable hierarchy:
-- dark navigation header, light artwork gallery, dark bottom tool strip,
-- and tapping a thumbnail opens its detail before editing.
-- Layout, icons, text and all pixels are Inkora originals.
local G={
    bar={0.155,0.155,0.155},paper={0.960,0.956,0.919},
    ink={0.18,0.19,0.20},muted={0.53,0.54,0.53},
    blue={0.25,0.72,0.97},line={0.72,0.72,0.69},
    white={1,1,1},shade={0.88,0.87,0.83},selected={0.16,0.67,0.96},
}
local function galleryIcon(kind,x,y,s)
    love.graphics.setLineWidth(1.8)
    if kind=="plus" then
        love.graphics.line(x-s,y,x+s,y)
        love.graphics.line(x,y-s,x,y+s)
    elseif kind=="info" then
        love.graphics.circle("line",x,y,s)
        love.graphics.circle("fill",x,y-s*0.45,1.4)
        love.graphics.line(x,y-1,x,y+s*0.56)
    elseif kind=="share" then
        love.graphics.rectangle("line",x-s*0.72,y-s*0.15,s*1.44,s*0.98)
        love.graphics.line(x,y+s*0.15,x,y-s*1.0)
        love.graphics.line(x-s*0.38,y-s*0.64,x,y-s*1.04,x+s*0.38,y-s*0.64)
    elseif kind=="dots" then
        for offset=-1,1 do love.graphics.circle("fill",x+offset*s*0.80,y,2.1) end
    elseif kind=="play" then
        love.graphics.polygon("line",x-s*0.45,y-s*0.9,x+s*0.8,y,x-s*0.45,y+s*0.9)
    elseif kind=="back" then
        love.graphics.line(x+s*0.42,y-s*0.75,x-s*0.25,y,x+s*0.42,y+s*0.75)
    end
    love.graphics.setLineWidth(1)
end

-- Folders are saved as references to immutable project keys; no project
-- images or INKORA1 layers are moved or rewritten while organizing.
function Startup:galleryEntries()
    return self.folders:contents(self.projects,self.galleryFolder)
end
function Startup:galleryOpenFolder(id)
    if not self.folders.items[id] then return false end
    self.galleryFolder=id
    self.galleryScroll=0
    self.galleryDetailKey=nil
    self.gallerySelecting=false
    self.gallerySelected={}
    self.galleryMenu=false
    self.newMenu=false
    self.galleryDrag=nil
    self.notice=nil
    return true
end
function Startup:galleryBack(app)
    if self.galleryDetailKey then
        self.galleryDetailKey=nil
    elseif self.gallerySelecting then
        self:galleryToggleSelection()
    elseif self.galleryFolder~="" then
        self.galleryFolder=self.folders:parent(self.galleryFolder)
        self.galleryScroll=0
    else
        app.screen="home"
    end
    self.galleryMenu=false
    self.newMenu=false
end
function Startup:galleryNewMenu()
    self.galleryMenu=false
    self.newMenu=not self.newMenu
end
function Startup:galleryAskFolder(keys)
    self.newMenu=false
    self.galleryModal={kind="folder",value="Nova pasta",keys=keys}
end
function Startup:galleryCreateFolder()
    local modal=self.galleryModal
    if not modal or modal.kind~="folder" then return false end
    local ok,id=pcall(function()
        local result=self.folders:create(modal.value,self.galleryFolder)
        if modal.keys and #modal.keys>0 then
            self.folders:moveProjects(modal.keys,result)
        end
        return result
    end)
    if not ok then modal.error=tostring(id);return false end
    self.galleryModal=nil
    self.gallerySelected={}
    self.gallerySelecting=false
    self:refreshGallery()
    self.notice="Pasta criada com sucesso."
    return id
end
function Startup:galleryAskRenameFolder()
    if self.galleryFolder=="" then return end
    self.galleryMenu=false
    self.galleryModal={kind="folder-rename",id=self.galleryFolder,
        value=self.folders:name(self.galleryFolder)}
end
function Startup:galleryRenameFolder()
    local modal=self.galleryModal
    if not modal or modal.kind~="folder-rename" then return false end
    local ok,result=pcall(function()
        return self.folders:rename(modal.id,modal.value)
    end)
    if not ok then modal.error=tostring(result);return false end
    self.galleryModal=nil
    self.notice="Pasta renomeada."
    return true
end
function Startup:galleryDeleteEmptyFolder()
    if self.galleryFolder=="" then return end
    local folder=self.galleryFolder
    local parent=self.folders:parent(folder)
    local ok,err=pcall(function()self.folders:deleteEmpty(folder)end)
    if ok then
        self.galleryFolder=parent
        -- parent is captured before deletion
        if self.galleryFolder=="" then self.galleryScroll=0 end
        self.notice="Pasta vazia removida."
    else
        self.notice="Nao foi possivel remover: "..tostring(err)
    end
    self.galleryMenu=false
end
function Startup:galleryAskMove()
    local keys=self:gallerySelectedKeys()
    if self.galleryDetailKey then keys={self.galleryDetailKey} end
    if #keys==0 then return end
    self.galleryMenu=false
    self.galleryModal={kind="move",keys=keys,offset=0}
end
function Startup:galleryMoveKeys(keys,destination)
    local ok,err=pcall(function()
        self.folders:moveProjects(keys,destination)
    end)
    if not ok then
        self.notice="Erro movendo desenho: "..tostring(err)
        return false
    end
    self.galleryModal=nil
    self.gallerySelected={}
    self.gallerySelecting=false
    self.galleryDetailKey=nil
    self.galleryScroll=0
    self.notice=#keys.." desenho(s) movido(s) com sucesso."
    return true
end
function Startup:galleryMoveSelected(destination)
    if not self.galleryModal or self.galleryModal.kind~="move" then return end
    return self:galleryMoveKeys(self.galleryModal.keys,destination)
end
function Startup:galleryMoveFolder(id,destination)
    local ok,err=pcall(function()
        self.folders:moveFolder(id,destination)
    end)
    if ok then
        self.galleryFolder=destination
        self.notice="Pasta movida."
    else self.notice=tostring(err) end
end
function Startup:galleryProject(key)
    for _,p in ipairs(self.projects) do
        if p.key==key then return p end
    end
end
function Startup:galleryCurrentKey()
    if self.galleryDetailKey then return self.galleryDetailKey end
    for _,p in ipairs(self.projects) do
        if self.gallerySelected[p.key] then return p.key end
    end
    return nil
end
function Startup:gallerySelectedKeys()
    local keys={}
    for _,p in ipairs(self.projects) do
        if self.gallerySelected[p.key] then keys[#keys+1]=p.key end
    end
    return keys
end
function Startup:gallerySelectToggle(key)
    self.gallerySelected[key]=not self.gallerySelected[key] or nil
end
function Startup:galleryToggleSelection()
    self.gallerySelecting=not self.gallerySelecting
    self.gallerySelected={}
    self.galleryDetailKey=nil
    self.galleryMenu=false
end
function Startup:galleryOpenDetail(key)
    if self.gallerySelecting then self:gallerySelectToggle(key)
    else self.galleryDetailKey=key;self.galleryMenu=false end
end
function Startup:galleryEdit(app)
    local key=self:galleryCurrentKey()
    if key then
        if not app:openArtwork(key) then
            self.notice="Falha ao abrir a obra."
        end
    end
end
function Startup:galleryExport()
    local key=self:galleryCurrentKey()
    if not key then return end
    local ok,result=pcall(function()
        return Document.load(key):exportPNG()
    end)
    self.notice=ok and ("PNG exportado: "..result) or
        ("Falha ao exportar PNG: "..tostring(result))
end
function Startup:galleryRename()
    local key=self:galleryCurrentKey()
    local p=key and self:galleryProject(key)
    if not p then return end
    self.galleryMenu=false
    self.galleryModal={kind="rename",key=key,value=p.name}
end
function Startup:galleryDuplicate()
    local key=self:galleryCurrentKey()
    if not key then return end
    self.galleryMenu=false
    local ok,result=pcall(Document.duplicateProject,key)
    if not ok then
        self.notice="Falha ao duplicar: "..tostring(result)
        return
    end
    self:refreshGallery()
    self.gallerySelected={}
    self.gallerySelecting=false
    self.galleryDetailKey=result
    self.notice="Copia criada. A obra original foi preservada."
end
function Startup:galleryAskTrash()
    local keys=self:gallerySelectedKeys()
    if self.galleryDetailKey then keys={self.galleryDetailKey} end
    if #keys==0 then return end
    self.galleryMenu=false
    self.galleryModal={kind="trash",keys=keys}
end
function Startup:galleryTrashConfirmed()
    local modal=self.galleryModal
    if not modal or modal.kind~="trash" then return end
    local count=0
    local failure=nil
    for _,key in ipairs(modal.keys) do
        local ok,err=pcall(Document.trashProject,key)
        if ok then count=count+1 else failure=tostring(err) end
    end
    self.galleryModal=nil
    self:refreshGallery()
    self.galleryDetailKey=nil
    self.gallerySelecting=false
    self.gallerySelected={}
    self.notice=failure and ("Erro na lixeira: "..failure) or
        (count.." obra(s) movida(s) para a lixeira.")
end
function Startup:galleryRestore()
    self.galleryMenu=false
    local deleted=Document.listProjects("deleted")
    if #deleted==0 then
        self.notice="A lixeira esta vazia."
        return
    end
    local ok,result=pcall(Document.restoreProject,deleted[1].key)
    if not ok then self.notice="Falha ao restaurar: "..tostring(result);return end
    self:refreshGallery()
    self.galleryDetailKey=result
    self.notice="Obra restaurada da lixeira."
end
function Startup:galleryConfirmRename()
    local modal=self.galleryModal
    if not modal or modal.kind~="rename" then return end
    local ok,result=pcall(Document.renameProject,modal.key,modal.value)
    if not ok then
        modal.error=tostring(result)
        return
    end
    self.galleryModal=nil
    self:refreshGallery()
    self.notice="Nome alterado para "..result
end

function Startup:galleryTool(x,y,kind,action,disabled)
    love.graphics.setColor(disabled and {0.46,0.47,0.47} or G.blue)
    galleryIcon(kind,x+20,y+23,12)
    if not disabled and action then
        self:hit(x,y,40,46,"tool-"..kind,action)
    end
end

function Startup:galleryTile(project,x,y,thumbW,thumbH,index)
    local cardH=thumbH+33
    local mouseX,mouseY=love.mouse.getPosition()
    local hovered=inside(mouseX,mouseY,{x=x,y=y,w=thumbW,h=cardH})
    drawRect(x-2,y-2,thumbW+4,thumbH+4,G.line,1)
    drawRect(x,y,thumbW,thumbH,G.white,1)
    local img=self:thumbnail(project)
    if img then
        local iw,ih=img:getDimensions()
        local scale=math.min((thumbW-6)/iw,(thumbH-6)/ih)
        love.graphics.setColor(1,1,1,1)
        love.graphics.draw(img,x+(thumbW-iw*scale)/2,
            y+(thumbH-ih*scale)/2,0,scale,scale)
    else
