function Startup:keypressed(app,key)
    if app.screen=="gallery" then
        local modal=self.galleryModal
        if modal then
            if key=="escape" then self.galleryModal=nil
            elseif modal.kind=="move" then
                if modal.naming and key=="backspace" then
                    local utf8=require("utf8")
                    local n=utf8.offset(modal.newName,-1)
                    if n then modal.newName=modal.newName:sub(1,n-1) end
                elseif modal.naming and (key=="return" or key=="kpenter") then
                    local ok,id=pcall(function()
                        return self.folders:create(modal.newName,modal.target)
                    end)
                    if ok then modal.target=id;modal.naming=false
                    else modal.error=tostring(id) end
                elseif key=="return" or key=="kpenter" then
                    self:galleryMoveSelected(modal.target)
                end
            elseif modal.kind=="folder-info" then
                if key=="backspace" then
                    local utf8=require("utf8")
                    local n=utf8.offset(modal.value,-1)
                    if n then modal.value=modal.value:sub(1,n-1) end
                elseif key=="return" or key=="kpenter" then
                    self:galleryConfirmFolderInfo()
                end
            elseif modal.kind=="new" then
                if key=="tab" then
                    modal.focus=modal.focus=="width" and "height" or "width"
                elseif key=="backspace" and modal.focus then
                    self.draft[modal.focus]=self.draft[modal.focus]:sub(1,-2)
                elseif key=="return" or key=="kpenter" then
                    if self:submit(app) then self.galleryModal=nil end
                end
            elseif modal.kind=="rename" or modal.kind=="folder" or
                modal.kind=="folder-rename" then
                if key=="backspace" then
                    local utf8=require("utf8")
                    local at=utf8.offset(modal.value,-1)
                    if at then modal.value=modal.value:sub(1,at-1) end
                elseif key=="return" or key=="kpenter" then
                    if modal.kind=="rename" then self:galleryConfirmRename()
                    elseif modal.kind=="folder" then self:galleryCreateFolder()
                    else self:galleryRenameFolder() end
                end
            elseif modal.kind=="trash" and (key=="return" or key=="kpenter") then
                self:galleryTrashConfirmed()
            end
            return true
        end
        if key=="escape" then
            if self.galleryMenu then self.galleryMenu=false
            elseif self.galleryDetailKey then self.galleryDetailKey=nil
            elseif self.gallerySelecting then self:galleryToggleSelection()
            elseif self.galleryFolder~="" then
                self.galleryFolder=self.folders:parent(self.galleryFolder)
                self.galleryScroll=0
            else app.screen="home" end
            return true
        elseif key=="return" or key=="kpenter" then
            if self.galleryDetailKey then self:galleryEdit(app) end
            return true
        elseif key=="delete" or key=="backspace" then
            self:galleryAskTrash()
            return true
        end
    end
    if app.screen=="create" then
        if key=="escape" then self:openGallery(app);return true end
        local d=self.draft
        if key=="tab" then
            d.focus=d.focus=="width" and "height" or
                d.focus=="height" and "name" or "width"
            return true
        elseif key=="backspace" and d.focus then
            if d.focus=="name" then
                local utf8=require("utf8")
                local n=utf8.offset(d.name,-1)
                if n then d.name=d.name:sub(1,n-1) end
            else d[d.focus]=d[d.focus]:sub(1,-2);d.preset=nil end
            return true
        elseif key=="return" or key=="kpenter" then
            return self:submit(app)
        end
    end
    return false
end
function Startup:textinput(text)
    if self.galleryModal and self.galleryModal.kind=="move" and
        self.galleryModal.naming then
        local modal=self.galleryModal
        modal.newName=(modal.newName..text:gsub("[\r\n\t]"," ")):sub(1,64)
        return
    end
    if self.galleryModal and self.galleryModal.kind=="folder-info" then
        local modal=self.galleryModal
        modal.value=(modal.value..text:gsub("[\r\n\t]"," ")):sub(1,64)
        return
    end
    if self.galleryModal and self.galleryModal.kind=="new" then
        local focus=self.galleryModal.focus
        if focus=="width" or focus=="height" then
            self.draft[focus]=(self.draft[focus]..text:gsub("%D","")):sub(1,4)
            self.draft.preset=nil
            self.error=nil
        end
        return
    end
    if self.galleryModal and (self.galleryModal.kind=="rename" or
        self.galleryModal.kind=="folder" or
        self.galleryModal.kind=="folder-rename") then
        local modal=self.galleryModal
        modal.value=(modal.value..text:gsub("[\r\n\t]"," ")):sub(1,64)
        modal.error=nil
        return
    end
    local d=self.draft
    if d.focus=="name" then
        d.name=(d.name..text:gsub("[\r\n\t]","")):sub(1,64)
    elseif d.focus=="width" or d.focus=="height" then
        d[d.focus]=(d[d.focus]..text:gsub("%D","")):sub(1,4)
        d.preset=nil
    end
end
return Startup
