-- Drag artworks onto folders, onto another artwork to create a group,
-- or onto Back to send them to the parent folder.
function Startup:pointerPressed(x,y)
    if self.galleryModal then return self:click(x,y) end
    local hit
    for i=#self.hits,1,-1 do
        if inside(x,y,self.hits[i]) then hit=self.hits[i];break end
    end
    if hit and not self.gallerySelecting and not self.galleryDetailKey and
       (hit.kind:match("^gallery%-art%-") or
        hit.kind:match("^gallery%-folder%-")) then
        local index=tonumber(hit.kind:match("(%d+)$"))
        local entry=self:galleryEntries()[index]
        if entry then
            self.galleryDrag={entry=entry,x=x,y=y,ox=x,oy=y,
                active=false,action=hit.action}
            return true
        end
    end
    return self:click(x,y)
end
function Startup:pointerMoved(x,y)
    local d=self.galleryDrag
    if d then
        d.x,d.y=x,y
        if (x-d.ox)^2+(y-d.oy)^2>160 then d.active=true end
    end
end
function Startup:pointerReleased(x,y)
    local d=self.galleryDrag
    self.galleryDrag=nil
    if not d then return end
    if not d.active then d.action();return end
    local target
    for i=#self.hits,1,-1 do
        if inside(x,y,self.hits[i]) then target=self.hits[i];break end
    end
    if not target then return end
    local kind=target.kind or ""
    local entry=d.entry
    if kind=="back-home" and self.galleryFolder~="" then
        local parent=self.folders:parent(self.galleryFolder)
        if entry.kind=="art" then
            self:galleryMoveKeys({entry.key},parent)
        else
            local ok,err=pcall(function()
                self.folders:moveFolder(entry.id,parent)
            end)
            self.notice=ok and "Pasta movida para o nivel anterior." or tostring(err)
        end
        return
    end
    if kind:match("^gallery%-folder%-") then
        local index=tonumber(kind:match("(%d+)$"))
        local destination=self:galleryEntries()[index]
        if destination and destination.kind=="folder" and
            destination.id~=entry.id then
            if entry.kind=="art" then
                self:galleryMoveKeys({entry.key},destination.id)
            else
                local ok,err=pcall(function()
                    self.folders:moveFolder(entry.id,destination.id)
                end)
                self.notice=ok and "Subpasta movida." or
                    ("Nao foi possivel mover: "..tostring(err))
            end
        end
    elseif kind:match("^gallery%-art%-") and entry.kind=="art" then
        local index=tonumber(kind:match("(%d+)$"))
        local destination=self:galleryEntries()[index]
        if destination and destination.kind=="art" and
            destination.key~=entry.key then
            self:galleryAskFolder({entry.key,destination.key})
            self.notice="Escolha o nome da pasta para agrupar as duas obras."
        end
    end
end

function Startup:click(x,y)
    for i=#self.hits,1,-1 do
        local hit=self.hits[i]
        if inside(x,y,hit) then
            hit.action()
            return true
        end
    end
    return false
end
function Startup:wheel(delta)
    if self.galleryDetailKey or self.galleryModal then return end
    if self.galleryMaxScroll and self.galleryMaxScroll>0 then
        self.galleryScroll=clamp(self.galleryScroll-delta*75,0,self.galleryMaxScroll)
    end
end
function Startup:keypressed(app,key)
    if app.screen=="gallery" then
        local modal=self.galleryModal
        if modal then
            if key=="escape" then self.galleryModal=nil
            elseif modal.kind=="rename" or modal.kind=="folder" or
                modal.kind=="folder-rename" then
                if key=="backspace" then
                    local utf8=require("utf8")
                    local at=utf8.offset(modal.value,-1)
                    if at then modal.value=modal.value:sub(1,at-1) end
                elseif key=="return" or key=="kpenter" then
                    if modal.kind=="rename" then self:galleryConfirmRename()
                    elseif modal.kind=="folder" then self:galleryCreateFolder()
                    else self:galleryRenameFolder() end
                end
            elseif modal.kind=="trash" and (key=="return" or key=="kpenter") then
                self:galleryTrashConfirmed()
            end
            return true
        end
        if key=="escape" then
            if self.galleryMenu then self.galleryMenu=false
            elseif self.galleryDetailKey then self.galleryDetailKey=nil
            elseif self.gallerySelecting then self:galleryToggleSelection()
            elseif self.galleryFolder~="" then
                self.galleryFolder=self.folders:parent(self.galleryFolder)
                self.galleryScroll=0
            else app.screen="home" end
            return true
        elseif key=="return" or key=="kpenter" then
            if self.galleryDetailKey then self:galleryEdit(app) end
            return true
        elseif key=="delete" or key=="backspace" then
            self:galleryAskTrash()
            return true
        end
    end
    if app.screen=="create" then
        if key=="escape" then self:openGallery(app);return true end
        local d=self.draft
        if key=="tab" then
            d.focus=d.focus=="width" and "height" or
                d.focus=="height" and "name" or "width"
            return true
        elseif key=="backspace" and d.focus then
            if d.focus=="name" then
                local utf8=require("utf8")
                local n=utf8.offset(d.name,-1)
                if n then d.name=d.name:sub(1,n-1) end
            else d[d.focus]=d[d.focus]:sub(1,-2);d.preset=nil end
            return true
        elseif key=="return" or key=="kpenter" then
            return self:submit(app)
        end
    end
    return false
end
function Startup:textinput(text)
    if self.galleryModal and (self.galleryModal.kind=="rename" or
        self.galleryModal.kind=="folder" or
        self.galleryModal.kind=="folder-rename") then
        local modal=self.galleryModal
        modal.value=(modal.value..text:gsub("[\r\n\t]"," ")):sub(1,64)
        modal.error=nil
        return
    end
    local d=self.draft
    if d.focus=="name" then
        d.name=(d.name..text:gsub("[\r\n\t]","")):sub(1,64)
    elseif d.focus=="width" or d.focus=="height" then
        d[d.focus]=(d[d.focus]..text:gsub("%D","")):sub(1,4)
        d.preset=nil
    end
end
return Startup
